// Roteiro dos GIFs dos exercícios: o GIF no treino do aluno (com crédito,
// pausa, movimento reduzido e sem internet), a biblioteca do treinador (busca,
// criar com GIF, vincular e tirar GIF) e o app com o banco ainda sem o
// supabase/exercicios.sql. As contas puras ficam em contas-exercicios.mjs.
const path = require('path')
const fs = require('fs')
const { chromium } = require('playwright')

const BASE = process.env.BASE || 'http://localhost:3200'
const MOCK = 'http://localhost:54321'
const GIF_BASE = `${MOCK}/__gif`
const OUT = path.join(__dirname, '.output', 'shots')
const results = []
const problems = []

const check = (name, condition) => results.push(`${condition ? 'OK  ' : 'FAIL'} ${name}`)
const mock = async (route) => (await fetch(`${MOCK}${route}`)).json()
const exerciseRow = async (name) => (await mock('/__exercises')).find((row) => row.name === name)
async function shot(page, name) {
  await page.waitForTimeout(400)
  await page.screenshot({ path: path.join(OUT, `${name}.png`), fullPage: true })
}
async function login(page, email, password = '123456') {
  await page.goto(`${BASE}/login`)
  await page.fill('#email', email)
  await page.fill('#password', password)
  await page.click('button[type=submit]')
  await page.waitForURL((url) => !url.pathname.startsWith('/login'), { timeout: 60000 })
}

;(async () => {
  fs.mkdirSync(OUT, { recursive: true })
  const browser = await chromium.launch()
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  const page = await context.newPage()
  page.on('pageerror', (error) => problems.push(`pageerror @ ${page.url()}: ${error.message}`))
  page.on('console', (message) => {
    if (message.type() !== 'error') return
    const text = message.text()
    // Esperados: requisições sem internet e respostas de erro do Supabase falso.
    const expected = /\b(400|401|403|404|422|429)\b/.test(text) || /ERR_INTERNET_DISCONNECTED|Failed to fetch|net::ERR/i.test(text)
    if (!expected) problems.push(`console @ ${page.url()}: ${text}`)
  })
  const section = (name) => page.locator('section[aria-label]', { has: page.locator('h2', { hasText: name }) })
  const mediaButton = (name) => section(name).locator('button[aria-label="Ver execução do exercício"], button[aria-label="Esconder execução"]')
  const gifOf = (name) => page.locator(`img[alt="Movimento do exercício ${name}"]`)

  // ------------------------------------------------- GIF no treino do aluno
  await login(page, 'maria@teste.com')
  await mock('/__gifs')
  await page.goto(`${BASE}/student/workout/w-a`)
  await page.waitForSelector('text=Anterior')
  check('treino abre sem baixar GIF nenhum (o GIF só carrega ao abrir a execução)', (await mock('/__gifs')).length === 0)
  check('exercício sem GIF nem vídeo: sem botão de execução', (await mediaButton('Tríceps na Polia com Corda').count()) === 0)
  const crucifixo = mediaButton('Crucifixo com Halteres')
  check('exercício com GIF ganha o botão "Ver execução"', (await crucifixo.count()) === 1)
  check('botão de execução com 44 px de altura', ((await crucifixo.boundingBox())?.height ?? 0) >= 44)
  await crucifixo.click()
  const gif = gifOf('Crucifixo com Halteres')
  await gif.waitFor({ timeout: 10000 })
  await page.waitForFunction((alt) => document.querySelector(`img[alt="${alt}"]`)?.naturalWidth > 0, 'Movimento do exercício Crucifixo com Halteres', { timeout: 10000 })
  check('GIF vem da base configurada, pelo media_id', (await gif.getAttribute('src')) === `${GIF_BASE}/0308-yz9nUhF.gif`)
  check('GIF 180 × 180, lazy e decoding async', (await gif.getAttribute('width')) === '180' && (await gif.getAttribute('height')) === '180' && (await gif.getAttribute('loading')) === 'lazy' && (await gif.getAttribute('decoding')) === 'async')
  const panel = section('Crucifixo com Halteres').locator('figure')
  const credit = panel.locator('a', { hasText: '© Gym visual' })
  check('crédito "© Gym visual" com link para gymvisual.com', (await credit.count()) === 1 && (await credit.getAttribute('href')) === 'https://gymvisual.com/')
  check('crédito abre em outra aba com noopener', (await credit.getAttribute('target')) === '_blank' && /noopener/.test((await credit.getAttribute('rel')) ?? ''))
  const creditSize = await credit.evaluate((element) => parseFloat(getComputedStyle(element).fontSize))
  check(`crédito com letra de pelo menos 12 px (${creditSize} px)`, creditSize >= 12)
  const pause = panel.locator('button', { hasText: 'Pausar movimento' })
  check('GIF toca sozinho com botão "Pausar movimento" (44 px)', (await pause.count()) === 1 && ((await pause.boundingBox())?.height ?? 0) >= 44)
  await shot(page, 'x01-treino-gif')
  await pause.click()
  check('pausar troca o GIF por um quadro parado', (await gif.count()) === 0 && (await panel.locator('canvas[role=img]:not([hidden])').count()) === 1)
  check('quadro parado tem descrição', ((await panel.locator('canvas').getAttribute('aria-label')) ?? '').includes('(pausado)'))
  await panel.locator('button', { hasText: 'Ver movimento' }).click()
  await gif.waitFor()
  check('"Ver movimento" volta a tocar', (await gif.count()) === 1)

  const firstSet = section('Crucifixo com Halteres').locator('button[aria-label="Marcar série 1 como concluída"]')
  await firstSet.click()
  await page.waitForSelector('section[aria-label="Crucifixo com Halteres"] button[aria-label="Desmarcar série 1"]', { timeout: 10000 })
  check('com o GIF aberto, a série continua sendo marcada', (await gif.count()) === 1)

  await mediaButton('Supino Reto com Barra').click()
  await page.waitForSelector('iframe[title^="Demonstração"]')
  check('vídeo do treinador tem prioridade sobre o GIF', (await gifOf('Supino Reto com Barra').count()) === 0)

  // ------------------------------------------------- movimento reduzido
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.reload()
  await page.waitForSelector('text=Anterior')
  await mock('/__gifs')
  await mediaButton('Crucifixo com Halteres').click()
  const still = section('Crucifixo com Halteres').locator('figure')
  await still.waitFor()
  await page.waitForTimeout(600)
  check('movimento reduzido: o GIF não toca sozinho', (await gifOf('Crucifixo com Halteres').count()) === 0)
  check('movimento reduzido: nem baixa o GIF antes de pedir', (await mock('/__gifs')).length === 0)
  check('movimento reduzido: crédito continua visível', (await still.locator('a', { hasText: '© Gym visual' }).isVisible()))
  const show = still.locator('button', { hasText: 'Ver movimento' })
  check('movimento reduzido: botão "Ver movimento" com 44 px', (await show.count()) === 1 && ((await show.boundingBox())?.height ?? 0) >= 44)
  await shot(page, 'x02-treino-movimento-reduzido')
  await show.click()
  await gifOf('Crucifixo com Halteres').waitFor({ timeout: 10000 })
  check('movimento reduzido: tocar em "Ver movimento" mostra o GIF', (await gifOf('Crucifixo com Halteres').count()) === 1)
  await page.emulateMedia({ reducedMotion: 'no-preference' })

  // ------------------------------------------------- sem internet
  await page.goto(`${BASE}/student/workout/w-b`)
  await page.waitForSelector('text=Anterior')
  await page.waitForFunction(() => navigator.serviceWorker?.controller != null, null, { timeout: 30000 })
  await page.waitForTimeout(1200)
  await context.setOffline(true)
  await page.reload()
  await page.waitForSelector('text=Anterior', { timeout: 30000 })
  check('sem internet, o treino abre (cópia do aparelho)', (await section('Puxada Frontal').count()) === 1)
  const puxada = mediaButton('Puxada Frontal')
  check('sem internet, o botão de execução aparece (media_id veio na cópia)', (await puxada.count()) === 1)
  await puxada.click()
  await puxada.first().waitFor({ state: 'detached', timeout: 10000 })
  check('sem internet, o GIF que falhou some com o botão, sem buraco', (await gifOf('Puxada Frontal').count()) === 0 && (await section('Puxada Frontal').locator('figure').count()) === 0)
  const offlineSet = section('Puxada Frontal').locator('button[aria-label="Marcar série 1 como concluída"]')
  await offlineSet.click()
  await page.waitForSelector('section[aria-label="Puxada Frontal"] button[aria-label="Desmarcar série 1"]', { timeout: 10000 })
  check('sem internet, a série é marcada mesmo com o GIF falho', true)
  await shot(page, 'x03-treino-offline-sem-gif')
  await context.setOffline(false)
  await page.waitForTimeout(2500)

  // ------------------------------------------------- banco sem o exercicios.sql
  await mock('/__exercicios/off')
  await page.goto(`${BASE}/student/workout/w-a`)
  await page.waitForSelector('text=Anterior')
  check('sem a coluna media_id: treino abre normal e sem GIF', (await mediaButton('Crucifixo com Halteres').count()) === 0 && (await mediaButton('Supino Reto com Barra').count()) === 1)
  await mock('/__exercicios/on')

  // ------------------------------------------------- biblioteca do treinador
  await context.clearCookies()
  await page.evaluate(() => localStorage.clear())
  await login(page, 'jean@teste.com')
  await page.goto(`${BASE}/admin/exercises`)
  await page.waitForSelector('text=Supino Reto com Barra')
  check('cabeçalho conta os exercícios com GIF', (await page.textContent('main')).includes('3 com GIF'))
  check('cartões com GIF ganham a etiqueta', (await page.locator('main ul button', { hasText: 'GIF' }).count()) === 3)
  const openLibrary = page.locator('button', { hasText: 'Buscar na biblioteca' })
  check('botão "Buscar na biblioteca" com 44 px', ((await openLibrary.boundingBox())?.height ?? 0) >= 44)
  await openLibrary.click()
  const dialog = page.locator('[role=dialog]', { hasText: 'Buscar na biblioteca' })
  await dialog.locator('input[type=search]').waitFor({ timeout: 30000 })
  await dialog.locator('ul[aria-label="Resultados da biblioteca"] li').first().waitFor()
  check('biblioteca carrega 20 por vez', (await dialog.locator('ul[aria-label="Resultados da biblioteca"] > li').count()) === 20)
  check('mostra o total de 1.324', (await dialog.textContent()).includes('1324 exercícios encontrados · mostrando 20'))
  await dialog.locator('button', { hasText: /^Mostrar mais 20$/ }).click()
  check('"Mostrar mais" traz a próxima página', (await dialog.locator('ul[aria-label="Resultados da biblioteca"] > li').count()) === 40)
  await dialog.locator('[role=radio]', { hasText: 'Peito' }).click()
  await dialog.locator('select').selectOption('Halteres')
  const metas = await dialog.locator('ul[aria-label="Resultados da biblioteca"] > li p').allTextContents()
  check('filtro de grupo e equipamento', metas.length > 0 && metas.every((text) => text.includes('Peito · Halteres')))
  await dialog.locator('select').selectOption('Todos')
  await dialog.locator('[role=radio]', { hasText: 'Todos' }).click()
  await dialog.locator('input[type=search]').fill('supino')
  await dialog.locator('h3', { hasText: /^Supino Reto com Barra$/ }).waitFor()
  const existing = dialog.locator('li', { has: page.locator('h3', { hasText: /^Supino Reto com Barra$/ }) })
  check('busca "supino" acha o Supino Reto com Barra, já cadastrado', (await existing.textContent()).includes('Já cadastrado'))
  check('resultado mostra o GIF da biblioteca', (await existing.locator('img').getAttribute('src')) === `${GIF_BASE}/0025-EIeI8Vf.gif`)
  check('cada GIF da busca leva o crédito', (await existing.locator('a', { hasText: '© Gym visual' }).count()) === 1)
  await shot(page, 'x04-biblioteca-busca')
  await dialog.locator('input[type=search]').fill('supino inclinado barra')
  const create = dialog.locator('button[aria-label="Criar Supino Inclinado com Barra"]')
  await create.waitFor()
  await create.click()
  await page.waitForSelector('text=Exercício criado', { timeout: 10000 })
  const created = await exerciseRow('Supino Inclinado com Barra')
  check('cria o exercício com nome em português, grupo e media_id', created?.muscle_group === 'Peito' && created?.media_id === '0047-3TZduzM')
  await page.waitForSelector('main >> text=Supino Inclinado com Barra')
  check('o novo exercício aparece na biblioteca com GIF', (await page.textContent('main')).includes('4 com GIF'))

  // Vincular GIF a um exercício existente.
  await page.click('main button:has-text("Tríceps na Polia com Corda")')
  await page.click('[role=dialog] button:has-text("Editar exercício")')
  await page.waitForSelector('#exercise-name')
  await page.locator('[role=dialog] button', { hasText: 'Vincular GIF' }).click()
  const linkDialog = page.locator('[role=dialog]', { hasText: 'Escolha o movimento deste exercício' })
  await linkDialog.locator('input[type=search]').waitFor({ timeout: 30000 })
  await linkDialog.locator('input[type=search]').fill('triceps pulley corda')
  await linkDialog.locator('button[aria-label="Usar este GIF: Tríceps Pulley com Corda"]').click()
  await page.waitForSelector('[role=dialog] img[alt="Movimento do exercício Tríceps na Polia com Corda"]')
  check('"Vincular GIF" mostra a prévia no editor', true)
  await shot(page, 'x05-editor-gif')
  await page.click('[role=dialog] button[type=submit]')
  await page.waitForSelector('text=Exercício atualizado', { timeout: 10000 })
  check('salvar grava o media_id escolhido', (await exerciseRow('Tríceps na Polia com Corda'))?.media_id === '0200-dU605di')

  await page.click('main button:has-text("Tríceps na Polia com Corda")')
  await page.waitForSelector('[role=dialog] img[alt="Movimento do exercício Tríceps na Polia com Corda"]')
  check('detalhe do exercício mostra o GIF', true)
  await page.click('[role=dialog] button:has-text("Editar exercício")')
  await page.locator('[role=dialog] button', { hasText: 'Tirar GIF' }).click()
  await page.click('[role=dialog] button[type=submit]')
  await page.waitForSelector('text=Exercício atualizado', { timeout: 10000 })
  await page.waitForTimeout(400)
  check('"Tirar GIF" volta o media_id para vazio', (await exerciseRow('Tríceps na Polia com Corda'))?.media_id === null)

  // media_id inválido é recusado pelo banco.
  const token = (await (await fetch(`${MOCK}/auth/v1/token?grant_type=password`, { method: 'POST', body: JSON.stringify({ email: 'jean@teste.com', password: '123456' }) })).json()).access_token
  const patch = (media_id) =>
    fetch(`${MOCK}/rest/v1/exercises?id=eq.e2`, { method: 'PATCH', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ media_id }) }).then(async (response) => ({ status: response.status, body: await response.json() }))
  const slash = await patch('videos/0308-yz9nUhF')
  const link = await patch('http://malicioso.com/x.gif')
  check('media_id com "/" é recusado (23514)', slash.status === 400 && slash.body.code === '23514' && /exercises_media_id_check/.test(slash.body.message))
  check('media_id com endereço (http) é recusado (23514)', link.status === 400 && link.body.code === '23514')
  check('media_id continua o mesmo depois das recusas', (await exerciseRow('Crucifixo com Halteres'))?.media_id === '0308-yz9nUhF')
  const studentToken = (await (await fetch(`${MOCK}/auth/v1/token?grant_type=password`, { method: 'POST', body: JSON.stringify({ email: 'maria@teste.com', password: '123456' }) })).json()).access_token
  const studentPatch = await fetch(`${MOCK}/rest/v1/exercises?id=eq.e2`, { method: 'PATCH', headers: { Authorization: `Bearer ${studentToken}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ media_id: '0001-2gPfomN' }) })
  check('aluna não troca o GIF de um exercício', studentPatch.status === 403 && (await exerciseRow('Crucifixo com Halteres'))?.media_id === '0308-yz9nUhF')

  // ------------------------------------------------- treinador sem o exercicios.sql
  await mock('/__exercicios/off')
  await page.goto(`${BASE}/admin/exercises`)
  await page.waitForSelector('text=Supino Reto com Barra')
  check('sem o SQL: aviso amigável para rodar o supabase/exercicios.sql', (await page.textContent('main')).includes('rode o arquivo supabase/exercicios.sql no Supabase'))
  check('sem o SQL: nenhum cartão com etiqueta de GIF', (await page.locator('main ul button', { hasText: 'GIF' }).count()) === 0)
  await page.click('main button:has-text("Prancha")')
  await page.click('[role=dialog] button:has-text("Editar exercício")')
  await page.waitForSelector('#exercise-name')
  // O diálogo de detalhe pode ainda estar saindo: confere só o diálogo do editor.
  const editorDialog = page.locator('[role=dialog]', { has: page.locator('#exercise-name') })
  await editorDialog.locator('text=supabase/exercicios.sql').waitFor()
  check('sem o SQL: editor mostra o aviso no lugar do "Vincular GIF"', (await editorDialog.locator('button', { hasText: 'Vincular GIF' }).count()) === 0 && (await editorDialog.textContent()).includes('supabase/exercicios.sql'))
  await page.fill('#exercise-name', 'Prancha Frontal')
  await page.click('[role=dialog] button[type=submit]')
  await page.waitForSelector('text=Exercício atualizado', { timeout: 10000 })
  check('sem o SQL: editar o resto do exercício continua funcionando', Boolean(await exerciseRow('Prancha Frontal')))
  await page.locator('button', { hasText: 'Buscar na biblioteca' }).click()
  const offDialog = page.locator('[role=dialog]', { hasText: 'Buscar na biblioteca' })
  await offDialog.locator('input[type=search]').waitFor({ timeout: 30000 })
  check('sem o SQL: a busca avisa que entra sem GIF', (await offDialog.textContent()).includes('entram sem GIF'))
  await offDialog.locator('input[type=search]').fill('rosca martelo com halteres')
  await offDialog.locator('button[aria-label="Criar Rosca Martelo com Halteres"]').click()
  await page.waitForSelector('text=ainda sem GIF', { timeout: 10000 })
  const noGif = await exerciseRow('Rosca Martelo com Halteres')
  check('sem o SQL: cria pela biblioteca, sem o GIF', noGif?.muscle_group === 'Bíceps' && noGif?.media_id === null)
  await mock('/__exercicios/on')

  await browser.close()
  console.log(results.join('\n'))
  console.log('\nPROBLEMAS DE CONSOLE/PÁGINA:', problems.length ? '\n' + problems.join('\n') : 'nenhum')
  const failed = results.filter((line) => line.startsWith('FAIL')).length
  console.log(`\n${results.length - failed} de ${results.length} verificações OK`)
  if (failed > 0 || problems.length > 0) process.exitCode = 1
})().catch((error) => {
  console.log(results.join('\n'))
  console.log('\nPROBLEMAS:', problems.join('\n'))
  console.error('ERRO NO ROTEIRO:', error.message)
  process.exit(1)
})
