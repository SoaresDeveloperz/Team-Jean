// Auditoria axe (WCAG 2.1 A/AA) das telas de gestão: senha, push, ficha de
// saúde, avaliação, treino offline com recado, recados do treinador,
// financeiro e o layout do treinador no computador.
const { chromium } = require('playwright')
const { createDevice, fakePushScript } = require('../push-decrypt.cjs')

const BASE = process.env.BASE || 'http://localhost:3200'
const MOCK = 'http://localhost:54321'
const { runAxe } = require('./run-axe.cjs')

;(async () => {
  const device = createDevice()
  const browser = await chromium.launch()
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: BASE })
  await context.addInitScript(fakePushScript({ endpoint: `${MOCK}/__push/a11y`, p256dh: device.p256dh, auth: device.authKey }))
  const page = await context.newPage()
  let total = 0
  const audit = async (label) => {
    await page.waitForTimeout(900)
    const result = await runAxe(page)
    total += result.length
    console.log(`== ${label}: ${result.length}`)
    for (const v of result) {
      console.log(`- [${v.impact}] ${v.id} (${v.count}): ${v.help}`)
      v.nodes.forEach((n) => console.log('    ' + n.slice(0, 240)))
    }
  }
  const login = async (email, password = '123456') => {
    await page.goto(BASE + '/login')
    await page.fill('#email', email)
    await page.fill('#password', password)
    await page.click('button[type=submit]')
    await page.waitForURL((u) => !u.pathname.startsWith('/login'), { timeout: 60000 })
  }
  const logout = async () => {
    await context.clearCookies()
    await page.evaluate(() => localStorage.clear())
  }

  // Acesso
  await page.goto(BASE + '/esqueci-senha')
  await audit('/esqueci-senha')
  await page.fill('#reset-email', 'maria@teste.com')
  await page.click('button:has-text("Enviar link")')
  await page.waitForSelector('text=Confira seu e-mail')
  await audit('esqueci a senha: enviado')
  await page.click('button:has-text("Usar outro e-mail")')
  await page.fill('#reset-email', 'maria@teste.com')
  await page.click('button:has-text("Enviar link")')
  await page.waitForSelector('main [role=alert]')
  await audit('esqueci a senha: limite de pedidos')
  // O alerta do limite ainda está na tela, mas com outro texto: esperar pelo texto novo basta.
  await page.fill('#reset-email', 'sem-smtp@teste.com')
  await page.click('button:has-text("Enviar link")')
  await page.waitForSelector('main [role=alert]:has-text("Não conseguimos enviar o e-mail agora")')
  await audit('esqueci a senha: e-mail não enviado')
  await page.goto(BASE + '/redefinir-senha')
  await page.waitForSelector('text=Link expirado')
  await audit('nova senha: link expirado')
  await page.goto(BASE + '/auth/confirm?token_hash=vencido&type=recovery')
  await page.waitForURL('**/login?erro=link')
  await audit('login com aviso de link vencido')
  await page.goto(BASE + '/auth/confirm?token_hash=recovery-u-student&type=recovery&next=/redefinir-senha')
  await page.waitForSelector('text=Crie sua senha nova')
  await page.fill('#new-password', 'NovaSenha2026')
  await page.fill('#confirm-password', 'diferente')
  await audit('nova senha: senhas diferentes')

  // Aluna (sessão aberta pelo link)
  await page.goto(BASE + '/student/today')
  await page.waitForSelector('text=Responda sua ficha de saúde')
  await audit('/student/today com lembrete da ficha')
  await page.goto(BASE + '/student/profile')
  await page.waitForSelector('button[role=switch][aria-label="Notificações no celular"]', { timeout: 30000 })
  await page.click('button[role=switch][aria-label="Notificações no celular"]')
  await page.waitForSelector('text=Enviar notificação de teste')
  await page.waitForSelector('text=Copiar código PIX')
  await page.click('button:has-text("Ver código")')
  await audit('perfil com push, mensalidade e PIX')
  await page.click('button:has-text("Ficha de saúde (PAR-Q)")')
  await page.waitForSelector('[role=dialog] >> text=PAR-Q')
  await page.click('[role=dialog] button:has-text("Salvar ficha")')
  await page.waitForSelector('[role=dialog] [role=alert]')
  await audit('ficha de saúde com erro')
  const groups = page.locator('[role=dialog] [role=radiogroup]')
  for (let index = 0; index < 7; index += 1) await groups.nth(index).locator('label', { hasText: index === 1 ? 'Sim' : 'Não' }).click()
  await page.click('[role=dialog] label:has-text("Diabetes")')
  await audit('ficha de saúde com alerta do PAR-Q')
  await page.click('[role=dialog] button:has-text("Salvar ficha")')
  await page.waitForSelector('text=Ficha de saúde salva')
  const measures = page.locator('section', { hasText: 'Medidas e evolução' }).first()
  await measures.locator('button:has-text("Registrar")').click()
  await page.waitForSelector('#measure-weight')
  await page.fill('#measure-weight', '66')
  await page.click('[role=dialog] button:has-text("Avaliação completa")')
  await page.click('[role=dialog] label:has-text("Feminino")')
  await page.fill('[role=dialog] input[id$="-birth"]', '1995-04-12')
  await page.fill('[role=dialog] input[id$="-height"]', '165')
  await page.click('[role=dialog] label:has-text("Pollock 7")')
  await audit('avaliação completa (faltando dobras)')
  for (const site of ['chest', 'midaxillary', 'triceps', 'subscapular', 'abdomen', 'suprailiac', 'thigh']) {
    await page.fill(`[role=dialog] input[id$="-fold-${site}"]`, '15')
  }
  await page.fill('[role=dialog] input[id$="-round-hip"]', '98')
  await audit('avaliação completa com % calculado')
  await page.click('[role=dialog] button:has-text("Salvar medidas")')
  await page.waitForSelector('text=Medidas salvas')
  await measures.locator('button[aria-label^="Ver avaliação completa de"]').first().click()
  await audit('histórico com a avaliação aberta')

  // Treino sem internet
  await page.goto(BASE + '/student/workout/w-b')
  await page.waitForSelector('text=Anterior')
  await page.waitForFunction(() => navigator.serviceWorker?.controller != null, null, { timeout: 30000 })
  await context.setOffline(true)
  await page.click('button[aria-label="Marcar série 1 como concluída"] >> nth=0')
  await page.waitForSelector('text=Sem internet: pode treinar normalmente')
  await audit('treino offline com série na fila')
  await page.click('button:has-text("Concluir")')
  await page.click('[role=dialog] button:has-text("Pesado demais")')
  await page.fill('[role=dialog] textarea', 'Último exercício pesado demais.')
  await audit('finalizar treino offline com recado')
  await page.click('[role=dialog] button:has-text("Salvar treino")')
  await page.waitForSelector('text=Treino salvo no aparelho')
  // O resumo entra em cascata (até ~1,1 s): audita depois da animação.
  await page.waitForTimeout(1200)
  await audit('resumo com o treino na fila')
  await context.setOffline(false)
  await page.waitForSelector('text=Conexão de volta', { timeout: 30000 })
  await audit('resumo depois de sincronizar')

  // Treinador
  await logout()
  await login('jean@teste.com')
  await page.goto(BASE + '/admin')
  const radar = page.locator('section', { hasText: 'Radar do treinador' })
  await page.waitForSelector('text=Último exercício pesado demais.', { timeout: 30000 })
  await audit('/admin com recados')
  await radar.locator('button:has-text("Responder")').first().click()
  await audit('responder recado')
  await radar.locator('button:has-text("Enviar resposta")').click()
  await page.waitForSelector('main [role=alert]')
  await audit('responder recado vazio')
  await page.goto(BASE + '/admin/students?aluno=u-student')
  await page.waitForSelector('[role=dialog] >> text=Último exercício pesado demais.')
  await audit('ficha: resumo com recado')
  await page.click('[role=dialog] [role=tab]:has-text("Saúde")')
  await page.waitForSelector('[role=dialog] >> text=PAR-Q com alerta')
  await audit('ficha: saúde')
  await page.click('[role=dialog] button:has-text("Editar")')
  await page.waitForSelector('text=Anamnese de Maria Souza')
  await audit('treinador editando a ficha de saúde')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(400)
  await page.click('[role=dialog] [role=tab]:has-text("Resumo")')
  await page.click('[role=dialog] button:has-text("Gerar senha nova")')
  await audit('confirmar senha nova')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(400)
  await page.keyboard.press('Escape')

  await page.goto(BASE + '/admin/finance')
  await page.waitForSelector('article[aria-label="Maria Souza"]')
  await audit('/admin/finance')
  await page.locator('article[aria-label="Maria Souza"] button:has-text("Receber")').click()
  await page.waitForSelector('#payment-amount')
  await page.fill('#payment-amount', 'abc')
  await page.click('[role=dialog] button:has-text("Confirmar recebimento")')
  await page.waitForSelector('[role=dialog] [role=alert]')
  await audit('registrar pagamento com erro')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(400)
  await page.locator('article[aria-label^="Carlos"] button:has-text("Plano")').click()
  await page.waitForSelector('#plan-fee')
  await audit('plano do aluno')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(400)
  await page.click('label:has-text("CPF")')
  await page.fill('#pix-key', '12')
  await page.click('button:has-text("Salvar recebimento")')
  await page.waitForSelector('text=Chave PIX inválida')
  await audit('PIX com chave inválida')
  await page.locator('article[aria-label="Maria Souza"] button:has-text("Receber")').click()
  await page.click('[role=dialog] button:has-text("Confirmar recebimento")')
  await page.waitForSelector('article[aria-label="Maria Souza"] >> text=Pago')
  await audit('/admin/finance com pagamento')

  // Computador
  await page.setViewportSize({ width: 1440, height: 900 })
  for (const route of ['/admin', '/admin/finance', '/admin/students', '/admin/workouts', '/admin/announcements', '/admin/community']) {
    await page.goto(BASE + route, { waitUntil: 'networkidle' })
    await page.waitForTimeout(1200)
    await audit(`computador ${route}`)
  }
  await page.goto(BASE + '/admin/students?aluno=u-student', { waitUntil: 'networkidle' })
  await page.waitForSelector('[role=dialog]')
  await audit('computador: ficha larga')

  console.log(`\nTOTAL DE VIOLAÇÕES: ${total}`)
  if (total > 0) process.exitCode = 1
  await browser.close()
})().catch((error) => {
  console.error('FALHOU:', error)
  process.exit(1)
})
